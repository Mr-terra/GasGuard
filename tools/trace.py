#!/usr/bin/env python3
"""Requirement traceability: REQ (docs) -> code (@req) -> tests (@verifies).

Writes docs/traceability.md. Exit code 1 if a requirement is not implemented
or not verified, or if a tag references an unknown requirement.
Use --allow-gaps to report without failing (early days of the plan).
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQ_DEF = re.compile(r"^\|\s*(REQ-[A-Z]{3}-\d{3})\s*\|", re.M)
REQ_TAG = re.compile(r"@(req|verifies)\s+((?:REQ-[A-Z]{3}-\d{3}[\s,]*)+)")
REQ_ID = re.compile(r"REQ-[A-Z]{3}-\d{3}")


def collect_tags(folder: Path, kind: str, pattern: str = "*.[ch]") -> dict:
    found: dict = {}
    if not folder.is_dir():
        return found
    for file in sorted(folder.rglob(pattern)):
        text = file.read_text(encoding="utf-8", errors="replace")
        for match in REQ_TAG.finditer(text):
            if match.group(1) != kind:
                continue
            line = text.count("\n", 0, match.start()) + 1
            for req in REQ_ID.findall(match.group(2)):
                found.setdefault(req, []).append(f"{file.relative_to(ROOT).as_posix()}:{line}")
    return found


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--allow-gaps", action="store_true")
    args = parser.parse_args()

    spec = (ROOT / "docs" / "01-requirements.md").read_text(encoding="utf-8")
    reqs = REQ_DEF.findall(spec)
    # Only a .c file counts as implementation: a header declares an interface,
    # it does not implement the requirement.
    code = collect_tags(ROOT, "req", "*.c")
    tests = collect_tags(ROOT / "tests", "verifies")

    known = set(reqs)
    orphans = sorted((set(code) | set(tests)) - known)
    not_impl = [r for r in reqs if r not in code]
    not_verif = [r for r in reqs if r not in tests]
    full = len(reqs) - len(set(not_impl) | set(not_verif))

    rows = ["| Requirement | Implemented in | Verified by |", "|---|---|---|"]
    for req in reqs:
        impl = "<br>".join(code.get(req, [])) or "**MISSING**"
        verif = "<br>".join(tests.get(req, [])) or "**MISSING**"
        rows.append(f"| {req} | {impl} | {verif} |")

    out = [
        "# Traceability matrix",
        "",
        "_Generated by `tools/trace.py` — do not edit by hand._",
        "",
        f"**{full}/{len(reqs)} requirements fully traced.**",
        "",
        *rows,
        "",
    ]
    if orphans:
        out += ["## Orphan tags (unknown requirement)", ""]
        out += [f"- {o}: {', '.join(code.get(o, []) + tests.get(o, []))}" for o in orphans]
        out.append("")
    (ROOT / "docs" / "traceability.md").write_text("\n".join(out), encoding="utf-8")

    print(f"Traceability: {full}/{len(reqs)} fully traced")
    print(f"  not implemented: {len(not_impl)}  not verified: {len(not_verif)}  orphans: {len(orphans)}")
    failed = bool(orphans) or (not args.allow_gaps and (not_impl or not_verif))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
